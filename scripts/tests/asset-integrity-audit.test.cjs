'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const {audit} = require('../asset-integrity-audit.cjs');

function fixture() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'zipeek-assets-'));
  const save = (name, bytes) => {
    const filename = path.join(root, name);
    fs.mkdirSync(path.dirname(filename), {recursive: true});
    fs.writeFileSync(filename, bytes);
  };
  const file = (name, bytes) => ({path: name, size_bytes: Buffer.byteLength(bytes), sha256: crypto.createHash('sha256').update(bytes).digest('hex')});
  const source = 'crates/zipeek-web/static/';
  const sourceItems = ['ATTRIBUTION.md', 'INPUTS.toml'].map(name => {
    const bytes = `content ${name}`;
    save(source + name, bytes);
    return file(name, bytes);
  });
  sourceItems.push(file('hanzi.duckdb.gz', 'generated bytes'));
  save(source + 'hanzi.manifest.json', JSON.stringify({files: sourceItems}));
  save('crates/zipeek-web/index.html', '<link rel="preload" href="hanzi.manifest.json"><link rel="preload" href="hanzi.duckdb.gz">');
  const png = Buffer.concat([Buffer.from('89504e470d0a1a0a', 'hex'), Buffer.from('0000000d494844520000000100000001', 'hex')]);
  for (const name of ['grammar-autumn-bridge', 'vocabulary-peony-garden', 'pinyin-landscape']) save(source + `courses/${name}.png`, png);
  for (const name of ['dragon', 'qilin', 'phoenix', 'white-tiger', 'crane', 'deer']) save(source + `practice/${name}.webp`, Buffer.concat([Buffer.from('RIFF'), Buffer.alloc(4), Buffer.from('WEBP'), Buffer.alloc(22)]));
  return {root, save, source};
}
function inFixture(fn) {
  const f = fixture();
  try { fn(f); } finally { fs.rmSync(f.root, {recursive: true, force: true}); }
}

test('source audit passes with explicit generated-asset notices', () => inFixture(({root}) => {
  const result = audit(root);
  assert.equal(result.passed, true);
  assert.ok(result.findings.some(f => f.code === 'GENERATED_ASSET_ABSENT'));
  assert.ok(result.findings.some(f => f.code === 'WORKER_NOT_BUILT'));
}));

test('deploy gate rejects ungenerated dictionary, worker and geography', () => inFixture(({root}) => {
  const result = audit(root, 'deploy');
  assert.equal(result.passed, false);
  assert.ok(result.findings.some(f => f.code === 'GEOGRAPHY_NOT_BUILT' && f.severity === 'error'));
}));

test('changed source data is detected by SHA-256', () => inFixture(({root, save, source}) => {
  save(source + 'ATTRIBUTION.md', 'DIFFERENT CONTENT');
  assert.ok(audit(root).findings.some(f => f.code === 'ASSET_SIZE_MISMATCH' || f.code === 'ASSET_HASH_MISMATCH'));
}));

test('missing manifest-declared source file is not silently accepted', () => inFixture(({root, source}) => {
  fs.unlinkSync(path.join(root, source, 'INPUTS.toml'));
  assert.equal(audit(root).passed, false);
}));

test('stale HTML database preload is rejected', () => inFixture(({root, save}) => {
  save('crates/zipeek-web/index.html', '<link rel="preload" href="hanzi.manifest.json"><link rel="preload" href="old.duckdb.gz">');
  assert.ok(audit(root).findings.some(f => f.code === 'STALE_DATABASE_PRELOAD'));
}));

test('manifest path traversal and duplicate entries are rejected', () => inFixture(({root, save, source}) => {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, source, 'hanzi.manifest.json'), 'utf8'));
  manifest.files.push({path: '../outside', size_bytes: 10, sha256: 'a'.repeat(64)});
  manifest.files.push(manifest.files[0]);
  save(source + 'hanzi.manifest.json', JSON.stringify(manifest));
  assert.equal(audit(root).findings.filter(f => f.code === 'INVALID_MANIFEST_PATH').length, 2);
}));

test('partial worker output is rejected in both modes', () => inFixture(({root, save}) => {
  save('crates/zipeek-web/static/pedagogy-worker/pedagogy_wasm.js', 'partial');
  assert.ok(audit(root).findings.some(f => f.code === 'PARTIAL_WORKER'));
}));

test('malformed geography JSON is not treated as missing', () => inFixture(({root, save}) => {
  save('crates/zipeek-web/static/province-quest/provinces.json', 'invalid');
  assert.ok(audit(root).findings.some(f => f.code === 'INVALID_GEOGRAPHY'));
}));
